from json_stream.httpx import load
from json_stream import to_standard_types
import httpx


class PyPISimpleJSONTransport(httpx.BaseTransport):
    def __init__(self, transport: httpx.BaseTransport) -> None:
        self._transport = transport

    def handle_request(self, request):
        if request.headers.get("Accept") != "application/vnd.pypi.simple.v1+json":
            request.headers["Accept"] = "application/vnd.pypi.simple.v1+json"
        return self._transport.handle_request(request)


client = httpx.Client(
    mounts={
        "https://pypi.org/simple/": PyPISimpleJSONTransport(httpx.HTTPTransport()),
    },
    follow_redirects=True,
)
with client.stream(
    "GET",
    "https://pypi.org/simple/rich/",
) as response:
    response.raise_for_status()
    d = load(response)
    print("# Generated by jss.py")
    for file in d["files"]:
        file = to_standard_types(file)
        # aria2c input file
        print(file["url"])
        print("\tcontinue=true")
        print("\tauto-file-renaming=false")
        print("\tallow-overwrite=false")
        print(f"\tchecksum=sha-256={file['hashes']['sha256']}")
        print(f"\tout={file['filename']}")
        print("\tsplit=16")
        print("\tmax-connection-per-server=16")
        print("\tdir=/tmp/pypi-repo")
