import json
import zipfile

APACHE_LISTS_BASE_URL = "https://lists.apache.org"
MAILING_LISTS_TARGET = {
    "httpd.apache.org": None,
    "arrow.apache.org": ["dev"],
    "airflow.apache.org": ["users"],
}
MAILING_MONTHS_TARGET = {"users@airflow.apache.org": {"2025-12", "2026-*"}}


def approved(domain, name):
    if domain not in MAILING_LISTS_TARGET:
        return False
    if MAILING_LISTS_TARGET[domain] is None:
        return True
    return name in MAILING_LISTS_TARGET[domain]


def match_month(domain, name, months) -> list[str]:
    list_name = f"{name}@{domain}"
    if list_name not in MAILING_MONTHS_TARGET:
        return months
    target_months = MAILING_MONTHS_TARGET[list_name]
    targets = []
    for t in target_months:
        year, month = t.split("-")
        if month == "*":
            targets.extend([m for m in months if m.startswith(year)])
        elif t in months:
            targets.append(t)
    return targets


def build_targets(domain, name, data) -> list[dict[str, str]]:
    list_name = f"{name}@{domain}"
    months = match_month(domain, name, list(data["active_months"]))
    targets = []
    for m in months:
        targets.append(
            {
                "api_url": f"{APACHE_LISTS_BASE_URL}/api/mbox.lua?list={list_name}&date={m}",
                "dir": f"apache-mailing-list-mbox/{domain}/{name}",
                "out": f"{m}.mbox",
            }
        )
    return targets


def build_input():
    lines = []

    lines.append("# Generated by build_input.py")
    lines.append("")

    with zipfile.ZipFile("apache-mailing-list-stats.zip", "r") as zf:
        for file_info in zf.infolist():
            if file_info.is_dir():
                continue
            domain, name = file_info.filename.split("/")[1:]
            name, *_ = name.split(".")
            if not approved(domain, name):
                continue
            with zf.open(file_info) as f:
                data = json.load(f)
            targets = build_targets(domain, name, data)
            lines.append(f"# {name}@{domain}")

            for t in targets:
                lines.append("")
                lines.append(t["api_url"])
                lines.append(f"   dir={t['dir']}")
                lines.append(f"   out={t['out']}")
                lines.append("")
    return lines


if __name__ == "__main__":
    lines = build_input()
    with open("input.txt", "w") as f:
        f.write("\n".join(lines))
